"""Generate traceable plotting products and an interactive content-alignment demo.

python scripts/demo_content_regions.py --output /tmp/content-regions-demo --serve
Then open http://127.0.0.1:8766, select both image layers, Detect, confirm each,
and align Left in Content alignment. Values are illustrative, not measurements.
"""

from __future__ import annotations

import argparse
import json
import sys
from io import BytesIO
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

def plotting_products():
    """Each PNG is accompanied by independent Axes truth from its plotting script."""
    import matplotlib as mpl
    import numpy as np
    from matplotlib.backends.backend_agg import FigureCanvasAgg
    from matplotlib.figure import Figure

    products = []
    with mpl.rc_context({"font.family": "DejaVu Sans", "font.size": 10, "text.usetex": False}):
        for name, width, height, position, scale in [
            ("A · short labels", 620, 340, (.13, .24, .60, .58), 1),
            ("B · wide labels", 720, 400, (.30, .16, .49, .68), 2_500_000),
        ]:
            figure = Figure(figsize=(width / 100, height / 100), dpi=100, facecolor="white")
            FigureCanvasAgg(figure)
            ax = figure.add_axes(position)
            times = np.arange(0, 61, 5)
            response = (1 - np.exp(-times / 22)) * scale
            ax.plot(times, response, "o-", color="#257d90", markersize=4, linewidth=1.7, label="Response")
            ax.set(xlabel="Time (min)", ylabel="Signal (a.u.)" if scale == 1 else "Response per million cells\n(counts / mL)",
                   xlim=(0, 60), ylim=(0, scale))
            ax.ticklabel_format(axis="y", style="plain")
            ax.spines[["top", "right"]].set_visible(False)
            ax.legend(loc="upper left", bbox_to_anchor=(1.01, 1), frameon=False, fontsize=9)
            figure.text(.04, .94, name + " · illustrative kinetics", fontsize=12, weight="bold")
            figure.canvas.draw()
            bbox = ax.get_window_extent()
            truth = {"x": bbox.x0 / width, "y": 1 - bbox.y1 / height,
                     "width": bbox.width / width, "height": bbox.height / height}
            stream = BytesIO()
            figure.savefig(stream, format="png", dpi=100)
            products.append({"name": name, "width": width, "height": height, "png": stream.getvalue(),
                             "plotBounds": truth, "rows": [{"time": int(t), "response": float(y)} for t, y in zip(times, response)]})
    return products


def build_demo(output):
    from pylustrator.web.document import new_document
    from pylustrator.web.store import ProjectStore

    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    store = ProjectStore(output / "workspace")
    project = store.create_project("Plot-area alignment · reproducible demo", description="Generated by scripts/demo_content_regions.py. Illustrative kinetics; not experimental measurements.")
    doc = new_document("Different margins, preserved labels", 1000, 850)
    manifest = []
    for i, item in enumerate(plotting_products()):
        filename = f"panel-{'ab'[i]}.png"
        (output / filename).write_bytes(item["png"])
        imported = store.add_asset(project["id"], item["name"], item["png"], mime_type="image/png",
                                   provenance={"generator": "scripts/demo_content_regions.py", "illustrative": True})
        doc["elements"].append({"id": f"panel-{'ab'[i]}", "type": "image", "name": item["name"],
                                "x": 180, "y": 45 + i * 385, "width": item["width"] * .9,
                                "height": item["height"] * .9, "assetId": imported["asset"]["id"]})
        manifest.append({k: v for k, v in item.items() if k != "png"} | {"file": filename})
    project = store.get_project(project["id"])
    project = store.update_project(project["id"], project["revision"], document=doc)
    (output / "source-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (output / "before-project.json").write_text(json.dumps(store.export_bundle(project["id"]), indent=2) + "\n")
    return project, manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("/tmp/figreflow-content-demo"))
    parser.add_argument("--serve", action="store_true")
    parser.add_argument("--port", type=int, default=8766)
    args = parser.parse_args()
    project, _ = build_demo(args.output)
    print(f"Created demo project {project['id']} in {args.output}", flush=True)
    if args.serve:
        import uvicorn
        from pylustrator.web.app import create_app

        uvicorn.run(create_app(args.output / "workspace"), host="127.0.0.1", port=args.port)
